<?php

return [

    /*
     * Соединение, которое дампится. По умолчанию — то же, на котором работает
     * приложение; параметры подключения читаются из config('database.connections.*'),
     * а не из .env, чтобы команда работала с закешированным конфигом.
     */
    'connection' => env('BACKUP_CONNECTION', env('DB_CONNECTION', 'pgsql')),

    /*
     * Диск, на который кладутся дампы. Объявлен в config/filesystems.php и
     * смотрит в storage/app/backups. Опция --path у команды перекрывает его
     * одноразовым диском с указанным корнем.
     */
    'disk' => env('BACKUP_DISK', 'backups'),

    /*
     * Сколько последних дампов оставлять при ротации.
     */
    'keep' => (int) env('BACKUP_KEEP', 10),

    /*
     * Потолок времени на pg_dump. Дамп большой базы идёт минутами, поэтому
     * значение заметно выше обычных 60 секунд Symfony Process.
     */
    'timeout' => (int) env('BACKUP_TIMEOUT', 900),

    /*
     * Путь к бинарнику pg_dump. Мажорная версия клиента должна совпадать с
     * версией сервера, иначе pg_dump откажется работать.
     */
    'pg_dump' => env('BACKUP_PG_DUMP', 'pg_dump'),

    /*
     * Начало имени файла: aroma_2026-08-07_030000.sql.gz. Пусто — берётся имя
     * базы из настроек соединения.
     */
    'prefix' => env('BACKUP_PREFIX'),

    /*
     * Дамп меньше этого размера считается битым: файл удаляется, запуск идёт
     * в провал и старые копии не ротируются.
     */
    'min_bytes' => (int) env('BACKUP_MIN_BYTES', 1024),

];
